/**
 * ألفاظ سؤال البحث ذات المعنى (HKM-044، ونُقلت من tools/semantic.ts في HKM-062 لتبقى صرفة بلا قاعدة).
 * يستعملها hakeem_search (الدمج والتكملة) وhakeem_semantic_search (تغطية الألفاظ) وhakeem_research.
 */
import { normalizeAr } from "./tools/word-match";

export const QUERY_STOP = new Set(
  [
    "ما", "ماذا", "هل", "كيف", "متي", "كم", "اين", "لماذا", "من", "في", "على", "علي", "الى", "الي", "عن", "او", "و", "ثم", "ان",
    "اذا", "لو", "التي", "الذي", "هذا", "هذه", "ذلك", "تلك", "هو", "هي", "مع", "بين", "عند", "كل", "اي", "لا", "لم", "لن", "قد",
    "بعد", "قبل", "حتي", "غير", "عليه", "فيه", "له", "به", "نظام", "النظام", "الماده", "ماده", "حكم", "يجب", "يحق",
  ].map(normalizeAr),
);

/**
 * HKM-062: ألفاظ الحوار والاستفهام الدارجة (خليجية وفصيحة) التي لا تحمل موضوع السؤال. كانت تدخل ألفاظًا للسؤال
 * («ابحث»، «وش»، «أبغى»، «أقدر») فتنقص تغطية المادة الصحيحة وتأخذ مقعد الحصر اللفظي (أطول لفظين).
 */
export const COLLOQUIAL_STOP = new Set(
  [
    "وش", "ايش", "إيش", "شو", "شنو", "شلون", "ليش", "وين", "مين", "منو", "لمين", "اللي", "اللى", "الى", "ابي", "ابغى", "ابغا", "أبغى",
    "أبي", "ودي", "عطني", "اعطني", "أعطني", "ابحث", "ابحثلي", "لي", "اقدر", "أقدر", "يقدر", "تقدر", "يقدرون", "نقدر",
    "اعرف", "أعرف", "يعني", "طيب", "بس", "مثلا", "كذا", "شي", "شيء", "واحد", "وحده", "صار", "صارت", "عندي", "عنده", "عندها",
    "لازم", "يصير", "يطلع", "طلع", "طلعت", "اسوي", "أسوي", "نسوي", "يسوي", "تسوي", "سوى", "سوا", "مني", "منه", "ايه", "هذي",
    "ذي", "ممكن", "لو", "سمحت", "فضلك", "تكفى", "سؤال", "استفسار", "حكيم", "يا", "ياخي", "اخوي", "الحين", "توني", "تكون", "يكون",
  ].map(normalizeAr),
);

/** HKM-062: عبارات الطلب التي تسبق موضوع السؤال («ابحث لي عن»، «أبغى أعرف»)؛ تُحذف كلماتها متتاليةً أينما وردت. */
export const REQUEST_PHRASES: string[][] = [
  "ابحث لي عن", "ابحثلي عن", "ابحث عن", "ابحث لي", "دور لي على", "دورلي على", "ابي اعرف", "ابغى اعرف", "ابغا اعرف", "ودي اعرف",
  "حاب اعرف", "اريد ان اعرف", "اريد اعرف", "اريد معرفة", "قل لي", "ممكن تقول لي", "ممكن تخبرني", "لو سمحت", "من فضلك", "عندي سؤال",
  "الله يعافيك", "يعطيك العافية", "ما هو حكم", "ما حكم", "وش حكم", "ايش حكم",
]
  .map((p) => p.split(/\s+/).map(normalizeAr))
  .sort((a, b) => b.length - a.length);

const WORD_SPLIT = /[^ء-يa-zA-Z0-9]+/;

/** يحذف عبارات الطلب من قائمة كلمات مطبَّعة (أطول عبارة أولًا). */
export function dropRequestPhrases(words: string[]): string[] {
  const out: string[] = [];
  for (let i = 0; i < words.length; ) {
    const hit = REQUEST_PHRASES.find((p) => p.every((w, j) => words[i + j] === w));
    if (hit) {
      i += hit.length;
      continue;
    }
    out.push(words[i]);
    i++;
  }
  return out;
}

/** ألفاظ السؤال ذات المعنى (بلا أدوات الاستفهام والحروف، ولا عبارات الطلب والحوار الدارجة — HKM-062). */
export function queryKeywords(q: string): string[] {
  const words = dropRequestPhrases(normalizeAr(q).split(WORD_SPLIT).filter(Boolean)).filter(
    (w) => w.length >= 2 && !QUERY_STOP.has(w) && !COLLOQUIAL_STOP.has(w),
  );
  return [...new Set(words)].slice(0, 12);
}
