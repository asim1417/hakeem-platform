/** فهرسٌ مختصر (اسم + وصف) يُحقن في توجيه أداة load_skill. */
export function skillsIndex(): Array<{ name: string; description: string }> {
  return SKILLS.map((s) => ({ name: s.name, description: s.description }));
}

/** يُعيد منهج المهارة الكامل، أو null إن لم توجد. */
export function loadSkillGuide(name: string): string | null {
  const skill = SKILLS.find((s) => s.name === String(name || "").trim().toLowerCase());
  return skill ? skill.guide : null;
}
