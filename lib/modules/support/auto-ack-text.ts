/**
 * نص الرد التلقائي بعد أول رسالة عميل — بلا اعتماد على قاعدة البيانات.
 */

const GREETING_RE = /السلام\s*عليكم|السلام عليكم|سلام عليكم|مرحبا|أهلا/i;

export function buildSupportAutoAck(userBody: string): string {
  const greet = GREETING_RE.test(userBody.trim()) ? "وعليكم السلام ورحمة الله.\n\n" : "";
  return (
    `${greet}استلمنا رسالتك في صندوق دعم حكيم.` +
    ` سيراجعها الفريق ويردّ هنا في هذه المحادثة.` +
    ` يمكنك إبقاء النافذة مفتوحة أو العودة لاحقًا — ستظهر شارة على زر «الدعم» عند وصول الرد.`
  );
}
