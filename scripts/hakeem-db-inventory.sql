  SELECT DISTINCT t FROM expected_cols e
  WHERE NOT EXISTS (SELECT 1 FROM information_schema.tables x WHERE x.table_schema='public' AND x.table_name=e.t)
),
missing_cols AS (
  SELECT e.t, e.c FROM expected_cols e
  WHERE e.t NOT IN (SELECT t FROM missing_tables)
    AND NOT EXISTS (SELECT 1 FROM information_schema.columns x WHERE x.table_schema='public' AND x.table_name=e.t AND x.column_name=e.c)
),
missing_enums AS (
  SELECT e.typ, e.val FROM expected_enums e
  WHERE NOT EXISTS (SELECT 1 FROM pg_type ty JOIN pg_enum en ON en.enumtypid=ty.oid WHERE ty.typname=e.typ AND en.enumlabel=e.val)
)
