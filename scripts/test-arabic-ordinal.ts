/**
 * اختبارات محلّل الأعداد الترتيبية العربية — بوابة جودة الاستيراد.
 * التشغيل: npx tsx scripts/test-arabic-ordinal.ts
 */
import { parseArabicOrdinal, checkTitleAgainstNumber } from "../lib/modules/legal-core/arabic-ordinal";

const CASES: Array<[string, number]> = [
  ["المادة الأولى", 1], ["المادة الثانية", 2], ["المادة التاسعة", 9], ["المادة العاشرة", 10],
  ["المادة الحادية عشرة", 11], ["المادة الثانية عشرة", 12], ["المادة التاسعة عشرة", 19],
  ["المادة العشرون", 20], ["المادة الحادية والعشرون", 21], ["المادة السابعة والثلاثون", 37],
  ["المادة الخمسون", 50], ["المادة التاسعة والتسعون", 99], ["المادة المائة", 100],
  ["المادة الأولى بعد المائة", 101], ["المادة العاشرة بعد المائة", 110],
  ["المادة السابعة والستون بعد المائة", 167], ["المادة المائتان", 200],
  ["المادة السادسة والثلاثون بعد المائتين", 236], ["المادة السابعة والثلاثون بعد المائتين", 237],
  ["المادة الثامنة والثلاثون بعد المائتين", 238], ["المادة الأربعون بعد المائتين", 240],
  ["المادة الخامسة والستون بعد الأربعمائة", 465], ["المادة السادسة والستون بعد الأربعمائة", 466],
  ["المادة الثامنة والستون بعد الأربعمائة", 468], ["المادة التاسعة والستون بعد الأربعمائة", 469],
  ["المادة الرابعة والسبعون بعد الأربعمائة", 474], ["المادة الخامسة والسبعون بعد الأربعمائة", 475],
  ["المادة التاسعة عشرة بعد السبعمائة", 719], ["المادة العشرون بعد السبعمائة", 720],
  ["المادة الحادية والعشرون بعد السبعمائة", 721],
  ["المادة الثلاثمائة", 300], ["المادة الخمسمائة", 500], ["المادة التسعمائة", 900], ["المادة الألف", 1000],
  // تباينات إملائية يجب أن تُقبل
  ["المادة السادسة والستون بعد الاربعمائة", 466],
  ["المادة السادسه والستون بعد الأربعمئة", 466],
  ["المادة ٤٦٦", 466], ["المادة 466", 466],
];

let failed = 0;
for (const [title, expected] of CASES) {
  const got = parseArabicOrdinal(title);
  if (got !== expected) { failed++; console.error(`✗ ${title} → ${got} (المتوقع ${expected})`); }
}

// بوابة المطابقة: يجب أن تُرصد الإزاحة
const shifted = checkTitleAgainstNumber("المادة الثامنة والثلاثون بعد المائتين", 237);
if (shifted.status !== "mismatch" || shifted.offset !== 1) { failed++; console.error("✗ لم تُرصد إزاحة +1"); }
const exact = checkTitleAgainstNumber("المادة السادسة والثلاثون بعد المائتين", 236);
if (exact.status !== "match") { failed++; console.error("✗ رُفضت مطابقة صحيحة"); }

console.log(failed === 0 ? `✓ نجحت جميع الاختبارات (${CASES.length + 2})` : `✗ فشل ${failed}`);
process.exit(failed === 0 ? 0 : 1);
